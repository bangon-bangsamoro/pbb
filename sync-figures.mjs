const ZOOM_LABEL = 'Buksan nang buo'

function srcset(stem, ext) {
  return MANIFEST[stem].widths
    .map((w) => `assets/images/derived/${stem}-${w}.${ext} ${w}w`)
    .join(', ')
}

function figureBlock(slug, spec, isFirst) {
  const key = spec.key || 'main'
  const m = MANIFEST[spec.img]
  if (!m) throw new Error(`${slug}: no manifest entry for ${spec.img}`)
  const cls = [
    'page-figure',
    spec.full ? 'page-figure--full' : (spec.bleed ? 'page-figure--bleed' : ''),
    isFirst ? 'page-figure--lede' : '',
  ].filter(Boolean).join(' ')

  /* `sizes` must describe the width the image is actually PAINTED at, or the
     browser picks the wrong candidate from srcset — too small and it is
     blurry, too large and a phone pays for pixels it cannot show.
     A --full figure runs edge-to-edge to a 1600px cap; everything else falls
     back to the content column above the 800px breakpoint. */
  const sizes = spec.full
    ? '(max-width: 1600px) 100vw, 1600px'
    : '(max-width: 799px) 100vw, min(1120px, 92vw)'

  return `${start(key)}
  <figure class="${cls}">
    <a class="page-figure__zoom" href="assets/images/${m.source}"
       data-zoom-label="${ZOOM_LABEL}"
       aria-label="${ZOOM_LABEL} ang larawan: ${spec.caption.replace(/"/g, '&quot;')}">
      <picture>
        <source type="image/webp" sizes="${sizes}" srcset="${srcset(spec.img, 'webp')}">
        <img src="assets/images/derived/${spec.img}-${m.widths[m.widths.length - 1]}.jpg"
             srcset="${srcset(spec.img, 'jpg')}"
             sizes="${sizes}"
             width="${m.width}" height="${m.height}"
             loading="${isFirst ? 'eager' : 'lazy'}"
             decoding="async"
             ${isFirst ? 'fetchpriority="high"' : ''}
             alt="${spec.alt.replace(/"/g, '&quot;')}">
      </picture>
    </a>
    <figcaption>${spec.caption}</figcaption>
  </figure>
  ${end(key)}`
}

/* --------------------------------------------------------------------------
   Insertion
   --------------------------------------------------------------------------
   A page may carry more than one figure. Each is keyed, wrapped in its own
   marker pair, and replaced in place — so re-running never stacks duplicates
   and adding a second figure does not disturb the first.

   Anchors:
     'hero'                 after the section that contains the page <h1>
     { before: 'sectionId'} immediately before <section ... id="sectionId">
     { after:  'sectionId'} immediately after that section's closing tag
   -------------------------------------------------------------------------- */

function blockRe(key) {
  const esc = (t) => t.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
  return new RegExp(esc(start(key)) + '[\\s\\S]*?' + esc(end(key)))
}

/** End of the section that contains the page's <h1>. */
function heroPoint(html) {
  const h1 = html.indexOf('<h1')
  if (h1 === -1) return -1
  const close = html.indexOf('</section>', h1)
  return close === -1 ? -1 : close + '</section>'.length
}

/** Start of `<section ... id="ID"`, walking back to the opening angle bracket. */
function sectionStart(html, id) {
  const at = html.search(new RegExp('<section[^>]*\\sid="' + id + '"'))
  return at
}

/** End of the section whose opening tag carries id="ID". Counts nesting. */
function sectionEnd(html, id) {
  const open = sectionStart(html, id)
  if (open === -1) return -1
  let depth = 0
  const re = /<\/?section\b/g
  re.lastIndex = open
  let m
  while ((m = re.exec(html))) {
    depth += m[0] === '</section' ? -1 : 1
    if (depth === 0) return html.indexOf('>', m.index) + 1
  }
  return -1
}

function anchorPoint(html, anchor, slug) {
  if (!anchor || anchor === 'hero') return heroPoint(html)
  if (anchor.before) {
    const at = sectionStart(html, anchor.before)
    if (at === -1) console.error(`${slug}: no <section id="${anchor.before}"> to anchor before`)
    return at
  }
  if (anchor.after) {
    const at = sectionEnd(html, anchor.after)
    if (at === -1) console.error(`${slug}: no <section id="${anchor.after}"> to anchor after`)
    return at
  }
  return -1
}

let changed = 0
let figureCount = 0
const stale = []

for (const [slug, entry] of Object.entries(FIGURES)) {
  const path = join(PUBLIC, slug)
  if (!existsSync(path)) { console.error('missing page:', slug); process.exit(1) }
  let html = readFileSync(path, 'utf8')
  const before = html

  // Migrate any unkeyed block written by the previous version.
  html = html.replace(LEGACY_RE, '')

  const specs = (Array.isArray(entry) ? entry : [entry]).map((sp, i) => ({
    ...sp, key: sp.key || (i === 0 ? 'main' : 'fig' + (i + 1)),
  }))

  /* Remove keyed blocks this page no longer declares. Without this, renaming
     or re-keying a figure leaves the old one behind — home.html briefly
     carried both a 'main' banner and its replacement. */
  const keep = new Set(specs.map((sp) => sp.key))
  html = html.replace(
    /<!-- PBB:FIGURE:START:([\w-]+)[\s\S]*?<!-- PBB:FIGURE:END:\1 -->/g,
    (whole, k) => (keep.has(k) ? whole : ''),
  )

  specs.forEach((spec, i) => {
    figureCount++
    const isLede = i === 0 && (!spec.anchor || spec.anchor === 'hero')
    const block = figureBlock(slug, spec, isLede)
    const re = blockRe(spec.key)
    if (re.test(html)) {
      html = html.replace(re, block)
      return
    }
    const at = anchorPoint(html, spec.anchor, slug)
    if (at === -1) {
      console.error(`${slug}: cannot place figure "${spec.key}" — no anchor found`)
      process.exit(1)
    }
    html = html.slice(0, at) + '\n\n  ' + block + '\n' + html.slice(at)
  })

  // Tidy the blank run the legacy strip can leave behind.
  html = html.replace(/\n{4,}/g, '\n\n\n')

  if (html !== before) {
    if (CHECK) stale.push(slug)
    else { writeFileSync(path, html); changed++ }
  }
}

if (CHECK) {
  if (stale.length) {
    console.error('Figures out of sync — run: node scripts/sync-figures.mjs')
    stale.forEach((s) => console.error('  ', s))
    process.exit(1)
  }
  console.log(`${Object.keys(FIGURES).length} pages / ${figureCount} figures checked — in sync`)
} else {
  console.log(`updated ${changed}/${Object.keys(FIGURES).length} pages, ${figureCount} figures`)
}
