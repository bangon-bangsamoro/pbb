/**
 * Places one campaign figure on every page in public/, consistently.
 *
 *   node scripts/sync-figures.mjs [--check]
 *
 * WHY THIS EXISTS
 *
 * Before this script, sixteen images sat in public/assets/images and the site
 * displayed exactly none of them. Eight were referenced only as og:image —
 * visible when a page was shared to Facebook, invisible to anyone who then
 * clicked through. Eight (Banner, Nashrudin, banner-modernity, banner-playbook,
 * campaign-tactics, halal-blueprint, legislative-architecture, modernity-bridge)
 * were referenced nowhere at all. The only <img> on most pages was the header
 * logo.
 *
 * HOW A FIGURE IS BUILT
 *
 * <picture> with a WebP source and a JPEG fallback, both with srcset across
 * the widths that exist for that file, plus width/height from the manifest so
 * the browser reserves the right box before the bytes arrive. The image is
 * never cropped: see section 10 of pbb-tokens.css for why that matters when
 * the artwork is a labelled diagram.
 *
 * Each figure is wrapped in a link to the full-size file. Voters reading a
 * five-node diagram on a 360px screen need to be able to open and zoom it,
 * and a plain link does that with no JavaScript, inside the Facebook in-app
 * browser, on any phone.
 *
 * ALT TEXT AND CAPTIONS ARE CONTENT, NOT DECORATION
 *
 * The meaning of these images is printed inside them as small text, which no
 * search engine and no screen reader can read. Every entry below therefore
 * carries alt text that states what the diagram claims, and a caption that
 * puts the same point in the page's own words. If you add an image, write
 * both. An empty alt on one of these hides a policy position from a blind
 * voter.
 *
 * The block is delimited by PBB:FIGURE markers and is regenerated in place,
 * so re-running this never stacks duplicates.
 */

